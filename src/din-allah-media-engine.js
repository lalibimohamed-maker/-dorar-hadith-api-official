import { createHash } from 'node:crypto';

export const MEDIA_PIPELINE = Object.freeze([
  'brief',
  'evidence_packet',
  'storyboard',
  'visual_source',
  'quality_evaluation',
  'quran_text',
  'verified_recitation',
  'sync',
  'composition',
  'master_validation',
  'human_review',
  'export'
]);

export const EXTERNAL_BENCHMARKS = Object.freeze({
  primary: 'VBench-2.0',
  secondary: 'VBench'
});

export const EXPORT_FORMATS = Object.freeze(['mp4', 'webm']);

const CLEAR_RIGHTS = new Set(['redistributable', 'licensed', 'public-domain']);

function nonEmpty(value) {
  return typeof value === 'string' && value.trim().length > 0;
}

function httpUrl(value) {
  try {
    const url = new URL(value);
    return url.protocol === 'http:' || url.protocol === 'https:';
  } catch {
    return false;
  }
}

function rightsCleared(rights) {
  return rights?.cleared === true ||
    (typeof rights?.status === 'string' && CLEAR_RIGHTS.has(rights.status));
}

function verifiedProvenance(provenance) {
  return Boolean(
    nonEmpty(provenance?.sourceId) &&
    nonEmpty(provenance?.citation) &&
    nonEmpty(provenance?.verifiedAt)
  );
}

function digest(value) {
  return createHash('sha256').update(value).digest('hex');
}

export function createBrief({ id, title, language = 'ar', objective, audience = 'general' } = {}) {
  if (!nonEmpty(id) || !nonEmpty(title) || !nonEmpty(objective)) {
    throw new TypeError('brief requires id, title and objective');
  }
  return Object.freeze({ id, title, language, objective, audience, generatedMediaCommitted: false });
}

export function createEvidencePacket({ claims = [], sources = [] } = {}) {
  if (!Array.isArray(claims) || !Array.isArray(sources)) {
    throw new TypeError('evidence packet requires claims and sources arrays');
  }
  const validSources = sources.every((source) =>
    nonEmpty(source?.id) &&
    (httpUrl(source?.url) || nonEmpty(source?.reference)) &&
    verifiedProvenance(source?.provenance)
  );
  if (!validSources) throw new TypeError('every evidence source requires provenance');
  const validClaims = claims.every((claim) =>
    nonEmpty(claim?.id) &&
    Array.isArray(claim.evidenceIds) &&
    claim.evidenceIds.length > 0
  );
  if (!validClaims) throw new TypeError('every claim requires explicit evidence ids');
  return Object.freeze({
    claims: Object.freeze(claims.map((claim) => Object.freeze({ ...claim, generatedSceneIsEvidence: false }))),
    sources: Object.freeze(sources.map((source) => Object.freeze({ ...source }))),
    uncertaintyExplicit: true
  });
}

export function createStoryboard({ scenes = [], evidencePacket } = {}) {
  if (!evidencePacket || !Array.isArray(scenes) || scenes.length === 0) {
    throw new TypeError('storyboard requires scenes and evidence packet');
  }
  const evidenceIds = new Set(evidencePacket.claims.flatMap((claim) => claim.evidenceIds));
  for (const scene of scenes) {
    if (!nonEmpty(scene?.id)) throw new TypeError('storyboard scene requires id');
    for (const claimId of scene.claimIds || []) {
      const claim = evidencePacket.claims.find((item) => item.id === claimId);
      if (!claim || !claim.evidenceIds.every((id) => evidenceIds.has(id))) {
        throw new TypeError(`scene claim is not grounded: ${claimId}`);
      }
    }
  }
  return Object.freeze({ scenes: Object.freeze(scenes.map((scene) => Object.freeze({ ...scene }))), evidencePacket });
}

export function evaluateVisualSource({ kind, provenance, rights, generated = false } = {}) {
  const failures = [];
  if (!['original', 'self-hosted-generation', 'imported'].includes(kind)) failures.push('visual_source_kind_invalid');
  if (!verifiedProvenance(provenance)) failures.push('visual_provenance_required');
  if (kind === 'imported' && !rightsCleared(rights)) failures.push('imported_visual_rights_not_cleared');
  if (generated && kind !== 'self-hosted-generation') failures.push('generated_kind_mismatch');
  return Object.freeze({ allowed: failures.length === 0, failures });
}

export function bindQuranText({
  text,
  sourceId,
  citation,
  verificationState = 'source_verified',
  sourceSha256,
  generated = false,
  rights
} = {}) {
  if (!nonEmpty(text) || !nonEmpty(sourceId) || !nonEmpty(citation)) {
    throw new TypeError('Quran text requires canonical text, source and citation');
  }
  if (generated) throw new TypeError('Quran text cannot be generated by the video model');
  if (!['source_verified', 'edition_verified', 'scholar_reviewed'].includes(verificationState)) {
    throw new TypeError('Quran text requires a verified source state');
  }
  if (!rightsCleared(rights)) throw new TypeError('Quran text distribution rights must be cleared');
  const actualSha256 = digest(text);
  if (sourceSha256 && sourceSha256 !== actualSha256) {
    throw new TypeError('Quran text fingerprint mismatch');
  }
  return Object.freeze({
    text,
    sourceId,
    citation,
    verificationState,
    sourceSha256: actualSha256,
    generated: false,
    canonical: true,
    rights
  });
}

export function bindVerifiedRecitation({ assetId, sourceUrl, provenance, rights, language = 'ar', audioSha256 } = {}) {
  if (!nonEmpty(assetId) || !httpUrl(sourceUrl)) throw new TypeError('recitation requires a source URL and asset id');
  if (language !== 'ar') throw new TypeError('Quran recitation must remain Arabic');
  if (!verifiedProvenance(provenance) || !rightsCleared(rights)) {
    throw new TypeError('recitation requires verified provenance and cleared rights');
  }
  return Object.freeze({
    assetId,
    sourceUrl,
    provenance,
    rights,
    language,
    audioSha256: audioSha256 || null,
    generated: false,
    verified: true
  });
}

export function evaluateSync({ quranText, recitation, timings, audioStreamIntegrity = false } = {}) {
  const failures = [];
  if (!quranText?.canonical || quranText.generated) failures.push('canonical_quran_required');
  if (!recitation?.verified || recitation.generated || recitation.language !== 'ar') failures.push('verified_arabic_recitation_required');
  if (!Array.isArray(timings) || timings.length === 0) failures.push('sync_timings_required');
  if (audioStreamIntegrity !== true) failures.push('audio_stream_integrity_required');
  return Object.freeze({ allowed: failures.length === 0, failures });
}

export function evaluateQuality({
  benchmark = {},
  customGates = {}
} = {}) {
  const failures = [];
  if (benchmark?.['VBench-2.0']?.reported !== true) failures.push('vbench_2_required');
  const gateNames = [
    'quranTextIntegrity',
    'recitationIntegrity',
    'provenance',
    'rights',
    'unintendedGeneratedText',
    'temporalConsistency',
    'audioStreamIntegrity'
  ];
  for (const name of gateNames) {
    if (customGates[name] !== true) failures.push(`custom_gate_failed:${name}`);
  }
  return Object.freeze({
    allowed: failures.length === 0,
    failures,
    benchmarkPolicy: Object.freeze({ primary: EXTERNAL_BENCHMARKS.primary, secondary: EXTERNAL_BENCHMARKS.secondary, ciDownloadsModels: false })
  });
}

export function validateMediaMaster({
  brief,
  storyboard,
  visualSource,
  quality,
  quranText,
  recitation,
  sync,
  humanReview = false
} = {}) {
  const failures = [];
  if (!brief?.id) failures.push('brief_required');
  if (!storyboard?.scenes?.length) failures.push('storyboard_required');
  if (!visualSource?.allowed) failures.push('visual_source_not_cleared');
  if (!quality?.allowed) failures.push(...(quality?.failures || ['quality_required']));
  if (!quranText?.canonical || quranText.generated) failures.push('quran_text_integrity_required');
  if (!recitation?.verified || recitation.generated) failures.push('recitation_integrity_required');
  if (!sync?.allowed) failures.push(...(sync?.failures || ['sync_required']));
  if (humanReview !== true) failures.push('human_review_required');
  return Object.freeze({
    allowed: failures.length === 0,
    state: failures.length === 0 ? 'validated-master' : 'blocked',
    failures,
    corpusMutation: false,
    generatedMediaCommitted: false
  });
}

export function authorizeExport({ master, format, visualRights = true, quranRights = true, recitationRights = true } = {}) {
  const normalized = String(format || '').toLowerCase();
  return Object.freeze({
    allowed: master?.state === 'validated-master' &&
      EXPORT_FORMATS.includes(normalized) &&
      visualRights === true &&
      quranRights === true &&
      recitationRights === true,
    format: normalized,
    corpusMutation: false
  });
}

export function mediaEngineCapability() {
  return Object.freeze({
    modelGenerationInCi: false,
    heavyVideoDownloadsInCi: false,
    generatedMediaInGit: false,
    runtimeDependencyAdded: false,
    corpusMutation: false,
    acquisitionBlocking: false,
    externalBenchmarkPrimary: EXTERNAL_BENCHMARKS.primary
  });
}
